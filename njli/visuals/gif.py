"""The GIF lane: ``njli new-gif <slug>`` and ``njli render <slug>`` for a HyperFrames project.

new-gif copies ``brand-kit/templates/gif-project`` into ``videos/<slug>``, syncs the motion library and the brand data
(fonts.css, brand.js, GSAP) into it. render runs the pinned HyperFrames (lint, check, render), makes the GIF with
ffmpeg (palettegen stats_mode=full, paletteuse dither=none), verifies it with ffprobe, swaps it in atomically and
removes every temp file on every exit path. A timeout kills the whole process tree.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
from pathlib import Path
from typing import Callable, Dict, List, Optional

from njli import atomic, policy

from . import MAX_FRAMES, VisualsError, assets, browser, fonts, kit_dir, probe, proc
from .render import _canvas, draft_dir, now_iso, read_meta

MOTION_FILES = ("core.js", "identity.js", "motion.css", "objects.data.js", "VERSION")
DATA_FILES = ("objects.data.js",)   # a project-local variant is never overwritten (new objects live in the project)
LEGACY_FILE = "motion.legacy.js"
TEMPLATE_TEXT = ("index.html", "shot-plan.json", "package.json")
TRIM_STEPS = ({"fps": 25, "colors": 256}, {"fps": 20, "colors": 256}, {"fps": 20, "colors": 192})


# ------------------------------------------------------------------ project files

def project_dir(workspace: Path, slug: str) -> Path:
    return Path(workspace) / "videos" / slug


def _fill(text: str, values: Dict[str, str]) -> str:
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def motion_source(workspace: Path) -> Path:
    """The workspace's managed copy (brand/motion) when present, else the shipped kit."""
    ws_copy = Path(workspace) / "brand" / "motion"
    return ws_copy if (ws_copy / "core.js").is_file() else kit_dir() / "motion"


def file_hash(path: Path) -> Optional[str]:
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None


def brand_js(cfg: dict, workspace: Path, project: Path) -> str:
    """The classic script that fills ``window.__brand`` from the config (the library has no defaults)."""
    ident = ((cfg.get("brand") or {}).get("identity")) or {}
    data: Dict[str, object] = {"identity": {}}
    if ident.get("enabled"):
        card = {"name": ident.get("name") or "", "role": ident.get("role") or ""}
        photo = ident.get("photo")
        if photo:
            src = Path(str(photo)).expanduser()
            src = src if src.is_absolute() else Path(workspace) / src
            if src.is_file():
                target = project / "motion" / ("photo" + src.suffix.lower())
                shutil.copyfile(src, target)
                card["photo"] = "./motion/" + target.name
        data["identity"] = card
    text = "/* GENERATED by njli from the brand config. Do not edit. */\nwindow.__brand = " + \
        json.dumps(data, ensure_ascii=False) + ";\n"
    sig = Path(workspace) / "brand" / "identity" / "signature.data.js"
    if ident.get("enabled") and sig.is_file():
        text += sig.read_text(encoding="utf-8")
    return text


def sync_motion(project: Path, workspace: Path, cfg: dict, legacy: bool = False) -> List[str]:
    """Copy the library into ``project/motion`` (data files by content hash) and write brand.js."""
    src = motion_source(workspace)
    dst = project / "motion"
    dst.mkdir(parents=True, exist_ok=True)
    copied: List[str] = []
    kept: List[str] = []
    names = list(MOTION_FILES) + ([LEGACY_FILE] if legacy or (dst / LEGACY_FILE).is_file() else [])
    for name in names:
        s = src / name
        if not s.is_file():
            raise VisualsError(f"motion library file missing: {s}")
        if name in DATA_FILES and (dst / name).is_file() and file_hash(s) != file_hash(dst / name):
            kept.append(name)
            continue
        if file_hash(s) != file_hash(dst / name):
            atomic.atomic_write_bytes(dst / name, s.read_bytes())
            copied.append(name)
    atomic.atomic_write_text(dst / "brand.js", brand_js(cfg, workspace, project))
    return copied


def prepare_project(project: Path, workspace: Path, cfg: dict, *, need_gsap: bool = True) -> dict:
    """Everything a render needs inside the project: motion lib, brand.js, fonts.css, vendored GSAP."""
    copied = sync_motion(project, workspace, cfg)
    plan = fonts.require(fonts.resolve(cfg, workspace))
    fonts.write_fonts_css(plan, project / "assets" / "fonts.css")
    gsap_src = None
    if need_gsap:
        gsap_src = assets.gsap_path(workspace)
        target = project / "vendor" / "gsap.min.js"
        if file_hash(gsap_src) != file_hash(target):
            atomic.atomic_write_bytes(target, gsap_src.read_bytes())
    return {"motion_copied": copied, "families": plan.family_names, "gsap": str(gsap_src) if gsap_src else None}


def new_gif(slug: str, workspace: Path, cfg: dict, *, title: str = "", lang: str = "en", force: bool = False) -> Path:
    if not re.match(r"^[a-z0-9][a-z0-9-]*$", slug):
        raise VisualsError("a slug is lowercase letters, digits and hyphens")
    project = project_dir(workspace, slug)
    if project.exists() and not force:
        raise VisualsError(f"{project} already exists (use --force to overwrite the template files)")
    tpl = kit_dir() / "templates" / "gif-project"
    if not tpl.is_dir():
        raise VisualsError(f"template missing: {tpl}")
    pins = assets.pins().get("npm") or {}
    values = {"slug": slug, "title": title or slug.replace("-", " "), "lang": "ar" if lang == "ar" else "en",
              "pin.hyperframes": pins.get("hyperframes", ""), "pin.gsap": pins.get("gsap", "")}
    project.mkdir(parents=True, exist_ok=True)
    for item in sorted(tpl.rglob("*")):
        rel = item.relative_to(tpl)
        target = project / rel
        if item.is_dir():
            target.mkdir(parents=True, exist_ok=True)
        elif item.name in TEMPLATE_TEXT or item.suffix in (".json", ".html"):
            atomic.atomic_write_text(target, _fill(item.read_text(encoding="utf-8"), values))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(item, target)
    sync_motion(project, workspace, cfg)
    return project


# ------------------------------------------------------------------ encode

def probe_frames(gif: Path, runner: Callable = proc.run) -> int:
    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        raise VisualsError("ffprobe not found: install ffmpeg (winget install Gyan.FFmpeg / brew install ffmpeg / apt install ffmpeg)")
    res = runner([ffprobe, "-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries",
                  "stream=nb_read_frames", "-of", "csv=p=0", str(gif)], timeout=300)
    n = res.stdout.strip().splitlines()[0].strip() if res.stdout.strip() else ""
    if not res.ok or res.stderr.strip() or not n.isdigit():
        raise VisualsError(f"{gif.name} does not decode: {(res.stderr or n or 'no frame count').strip()[:160]}")
    return int(n)


def probe_dims(gif: Path, runner: Callable = proc.run) -> Dict[str, int]:
    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        return {}
    res = runner([ffprobe, "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of",
                  "csv=p=0:s=x", str(gif)], timeout=120)
    m = re.match(r"^(\d+)x(\d+)", res.stdout.strip()) if res.ok else None
    return {"w": int(m.group(1)), "h": int(m.group(2))} if m else {}


def encode_gif(mp4: Path, out: Path, *, fps: int = 25, colors: int = 256, width: Optional[int] = None,
               max_frames: int = MAX_FRAMES, dither: str = "none", timeout: float = 1800,
               runner: Callable = proc.run) -> dict:
    """mp4 -> palette -> temp GIF -> ffprobe frame check -> atomic swap. Temp files never survive."""
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise VisualsError("ffmpeg not found: install ffmpeg (winget install Gyan.FFmpeg / brew install ffmpeg / apt install ffmpeg)")
    out.parent.mkdir(parents=True, exist_ok=True)
    pal = out.with_name(f"pal{colors}.png")
    tmp = out.with_suffix(".tmp.gif")
    chain = ",".join(x for x in (f"fps={fps}", f"scale={int(width)}:-2:flags=lanczos" if width else "") if x)
    try:
        r1 = runner([ffmpeg, "-v", "error", "-y", "-i", str(mp4), "-vf",
                     f"{chain},palettegen=max_colors={colors}:stats_mode=full", str(pal)], timeout=timeout)
        if not r1.ok:
            raise VisualsError(f"ffmpeg palettegen failed: {r1.tail()}")
        r2 = runner([ffmpeg, "-v", "error", "-y", "-i", str(mp4), "-i", str(pal), "-lavfi",
                     f"{chain}[x];[x][1:v]paletteuse=dither={dither}:diff_mode=rectangle", "-loop", "0",
                     str(tmp)], timeout=timeout)
        if not r2.ok:
            raise VisualsError(f"ffmpeg paletteuse failed: {r2.tail()}")
        frames = probe_frames(tmp, runner)
        if frames > max_frames:
            raise VisualsError(f"the GIF has {frames} frames (max {max_frames}); shorten the loop or lower the fps")
        if frames < 2:
            raise VisualsError(f"the GIF has {frames} frame(s); an animated GIF needs more")
        os.replace(tmp, out)
        return {"frames": frames, "bytes": out.stat().st_size, "fps": fps, "colors": colors}
    finally:
        for leftover in (pal, tmp):
            try:
                leftover.unlink()
            except OSError:
                pass


def encode_with_trim(mp4: Path, out: Path, cfg: dict, *, runner: Callable = proc.run) -> dict:
    """Encode at the configured settings; if over ``gate.gif.max_mb`` apply the documented trim pass."""
    g = ((cfg.get("render") or {}).get("gif")) or {}
    max_mb = float(((cfg.get("gate") or {}).get("gif") or {}).get("max_mb", 40))
    max_frames = int(((cfg.get("gate") or {}).get("gif") or {}).get("max_frames", MAX_FRAMES))
    steps = [{"fps": int(g.get("fps", 25)), "colors": int(g.get("colors", 256))}]
    steps += [s for s in TRIM_STEPS if s not in steps and s["fps"] <= steps[0]["fps"] and s["colors"] <= steps[0]["colors"]]
    tried = []
    for step in steps:
        info = encode_gif(mp4, out, fps=step["fps"], colors=step["colors"], width=g.get("width"),
                          max_frames=max_frames, dither=str(g.get("dither", "none")),
                          timeout=float((cfg.get("render") or {}).get("timeout_s", 1800)), runner=runner)
        info["width"] = g.get("width")
        info["dither"] = g.get("dither", "none")
        tried.append(f"{step['fps']} fps / {step['colors']} colours = {info['bytes'] / 2**20:.1f} MiB")
        if info["bytes"] <= max_mb * 1024 * 1024:
            info["trimmed"] = step != steps[0]
            return info
    try:
        out.unlink()
    except OSError:
        pass
    raise VisualsError(f"the GIF stays over {max_mb:g} MiB after the trim pass ({'; '.join(tried)}). "
                       "Simplify the motion (flat fills, fewer full-frame effects) or post an MP4 (planned for v1.1).")


# ------------------------------------------------------------------ render

def hyperframes_steps(project: Path, mp4: Path, chrome: browser.Browser, *, runner: Callable = proc.run,
                      timeout: float = 1800) -> None:
    env = {"HYPERFRAMES_BROWSER_PATH": str(chrome.path)}
    for label, args in (("lint", ["lint", "."]), ("check", ["check", "."]),
                        ("render", ["render", ".", "-q", "delivery", "--crf", "10", "--low-memory-mode", "-o",
                                    str(mp4.relative_to(project)) if mp4.is_relative_to(project) else str(mp4)])):
        res = runner(assets.hyperframes_cmd(*args), cwd=project, env=env, timeout=timeout)
        if res.timed_out:
            raise VisualsError(f"hyperframes {label} timed out after {timeout:.0f}s; its process tree was stopped")
        if not res.ok:
            raise VisualsError(f"hyperframes {label} failed (exit {res.returncode}): {res.tail(1200)}")


def versions(chrome: Optional[browser.Browser] = None) -> dict:
    ffmpeg = shutil.which("ffmpeg")
    ff = ""
    if ffmpeg:
        res = proc.run([ffmpeg, "-version"], timeout=30)
        ff = (res.stdout.splitlines() or [""])[0][:60]
    mv = ""
    try:
        mv = (kit_dir() / "motion" / "VERSION").read_text(encoding="utf-8").strip()
    except OSError:
        pass
    return {"hyperframes": assets.npm_pin("hyperframes"), "gsap": assets.npm_pin("gsap"), "node": assets.node_version(),
            "ffmpeg": ff, "motion": mv, "browser": chrome.source if chrome else None}


def asset_name(meta: dict, slug: str) -> str:
    return next((a for a in (meta.get("assets") or []) if str(a).endswith(".gif")), f"{slug}.gif")


def render_gif(slug: str, workspace: Path, cfg: dict, *, runner: Callable = proc.run,
               chrome: Optional[browser.Browser] = None) -> dict:
    draft = draft_dir(workspace, slug)
    meta = read_meta(draft)
    vp = meta.get("video_project")
    if not vp:
        raise VisualsError(f"drafts/{slug}/meta.json has no video_project")
    project = Path(workspace) / vp
    if not (project / "index.html").is_file():
        raise VisualsError(f"{project / 'index.html'} not found: create it with 'njli new-gif {slug}'")
    assets.require_node()
    chrome = chrome or browser.require(cfg, pin=assets.npm_pin("hyperframes"))
    prep = prepare_project(project, workspace, cfg)
    found = probe.problems(probe.run_probe(project, chrome, runner=runner))
    if found:
        raise VisualsError("the composition failed its own probe: " + "; ".join(found))
    mp4 = project / "renders" / "video.mp4"
    mp4.parent.mkdir(parents=True, exist_ok=True)
    hyperframes_steps(project, mp4, chrome, runner=runner, timeout=float((cfg.get("render") or {}).get("timeout_s", 1800)))
    if not mp4.is_file() or mp4.stat().st_size == 0:
        raise VisualsError("hyperframes finished but renders/video.mp4 is missing")
    name = asset_name(meta, slug)
    out_dir = draft / "out"
    info = encode_with_trim(mp4, out_dir / name, cfg, runner=runner)
    dims = probe_dims(out_dir / name, runner) or dict(zip(("w", "h"), _canvas(cfg)))
    data = {"slug": slug, "format": "gif", "rendered": now_iso(), "from": str(vp), "asset": name,
            "canvas": dims, "gif": info, "fonts": prep["families"], "versions": versions(chrome)}
    atomic.atomic_write_json(out_dir / "render.json", data)
    return data
