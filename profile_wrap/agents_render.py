"""``profile-wrap agents render``: write the agent templates into ``<workspace>/.claude/agents/``.

The plugin ships templates in ``agents/``. A template names a *tier* (``standard`` or ``economy``) and an
*effort*, never a model. Rendering looks the tier up in ``config.models`` and writes the alias, so changing
a model is one config edit followed by ``profile-wrap agents render``. The one shared rules file,
``agents/_standing-rules.md``, replaces the ``<!-- include: _standing-rules.md -->`` marker in every agent.

Rules enforced on every template (and by ``tools/build_agents.py --check`` in CI):

* no agent has a shell (``Bash``, ``PowerShell``) and none can spawn another (``Agent``, ``Task``);
* council seats are read-only apart from one findings file, and have no web tools;
* only researchers have web tools; only crew may use ``Edit``;
* ``disallowedTools`` always lists ``Bash``.
"""
from __future__ import annotations

import argparse
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional, Tuple

from . import claude_runner, config as cfgmod, paths, policy
from .atomic import atomic_write_text

INCLUDE_RE = re.compile(r"<!--\s*include:\s*([A-Za-z0-9_.-]+)\s*-->")
GENERATED_MARK = "<!-- generated by `profile-wrap agents render`"
TIERS = ("standard", "economy")
EFFORTS = ("low", "medium", "high")
NEVER_TOOLS = {"Bash", "PowerShell", "Agent", "Task", "SendMessage", "NotebookEdit", "KillShell"}
WEB_TOOLS = {"WebSearch", "WebFetch"}
SEAT_TOOLS = {"Read", "Glob", "Grep", "Write"}
STANDING = "_standing-rules.md"


class AgentError(ValueError):
    pass


@dataclass
class Template:
    name: str
    path: Path
    meta: Dict[str, str]
    body: str


@dataclass
class Rendered:
    name: str
    path: str
    status: str            # written | unchanged | would-write | refused | invalid
    detail: str = ""
    model: str = ""
    effort: str = ""
    tools: str = ""


@dataclass
class Report:
    items: List[Rendered] = field(default_factory=list)
    problems: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems and not any(i.status in ("refused", "invalid") for i in self.items)


# --------------------------------------------------------------------------- parsing

def _unquote(v: str) -> str:
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        v = v[1:-1]
        return v.replace('\\"', '"') if v else v
    return v


def parse_template(text: str, path: Path) -> Template:
    text = text.replace("\r\n", "\n").lstrip("﻿")
    if not text.startswith("---\n"):
        raise AgentError(f"{path.name}: missing the --- frontmatter block")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise AgentError(f"{path.name}: the frontmatter block is not closed")
    meta: Dict[str, str] = {}
    for line in text[4:end].splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            raise AgentError(f"{path.name}: bad frontmatter line {line!r}")
        k, v = line.split(":", 1)
        meta[k.strip()] = _unquote(v)
    return Template(name=meta.get("name", path.stem), path=path, meta=meta, body=text[end + 5:].lstrip("\n"))


def _tool_set(value: str) -> List[str]:
    return [t.strip() for t in value.split(",") if t.strip()]


def validate_template(t: Template) -> List[str]:
    probs: List[str] = []
    m = t.meta
    p = t.path.name
    if t.name != t.path.stem:
        probs.append(f"{p}: name '{t.name}' does not match the file name")
    for key in ("name", "description", "tier", "effort", "tools", "disallowedTools"):
        if not m.get(key):
            probs.append(f"{p}: frontmatter key '{key}' is missing")
    if m.get("tier") not in TIERS:
        probs.append(f"{p}: tier must be one of {', '.join(TIERS)}, not '{m.get('tier')}'")
    if m.get("effort") not in EFFORTS:
        probs.append(f"{p}: effort must be one of {', '.join(EFFORTS)}, not '{m.get('effort')}'")
    for forbidden in ("model",):
        if forbidden in m:
            probs.append(f"{p}: a template must not name a model; use tier and effort")
    tools = set(_tool_set(m.get("tools", "")))
    denied = set(_tool_set(m.get("disallowedTools", "")))
    bad = tools & NEVER_TOOLS
    if bad:
        probs.append(f"{p}: tools {sorted(bad)} are never allowed for an agent")
    if "Bash" not in denied:
        probs.append(f"{p}: disallowedTools must list Bash")
    if tools & denied:
        probs.append(f"{p}: tools and disallowedTools overlap on {sorted(tools & denied)}")
    kind = t.name.split("-", 1)[0]
    if tools & WEB_TOOLS and kind != "researcher":
        probs.append(f"{p}: only researchers have web tools")
    if "Edit" in tools and kind != "crew":
        probs.append(f"{p}: only crew agents may use Edit")
    if kind == "council" and not tools <= SEAT_TOOLS:
        probs.append(f"{p}: a council seat may use only {sorted(SEAT_TOOLS)}, not {sorted(tools - SEAT_TOOLS)}")
    if kind == "researcher" and "Write" not in tools:
        probs.append(f"{p}: a researcher must be able to write its research file")
    markers = INCLUDE_RE.findall(t.body)
    if markers != [STANDING]:
        probs.append(f"{p}: the body must include {STANDING} exactly once (found {markers or 'none'})")
    return probs


def load_templates(templates_dir: Optional[Path] = None) -> Tuple[List[Template], str]:
    base = Path(templates_dir) if templates_dir else paths.resource("agents")
    standing = base / STANDING
    if not standing.is_file():
        raise AgentError(f"{STANDING} not found in {base}")
    out: List[Template] = []
    for f in sorted(base.glob("*.md")):
        if f.name.startswith("_"):
            continue
        out.append(parse_template(f.read_text(encoding="utf-8"), f))
    if not out:
        raise AgentError(f"no agent templates in {base}")
    return out, standing.read_text(encoding="utf-8").strip() + "\n"


# --------------------------------------------------------------------------- rendering

def render_agent(t: Template, cfg: Mapping[str, Any], standing: str) -> Tuple[str, Dict[str, str]]:
    tier = t.meta["tier"]
    model = claude_runner.resolve_model(cfg, tier)
    effort = claude_runner.agent_effort(cfg, tier, t.meta.get("effort"))
    front = [
        "---",
        f"name: {t.name}",
        f"description: {json.dumps(t.meta['description'], ensure_ascii=False)}",
        f"model: {model['alias']}",
        f"effort: {effort}",
        f"tools: {t.meta['tools']}",
        f"disallowedTools: {t.meta['disallowedTools']}",
        "---",
        "",
        f"{GENERATED_MARK} from agents/{t.path.name}. "
        f"Change models in config/profile-wrap.json (models) and run it again; do not edit this file. -->",
        "",
    ]
    block = "## Standing rules\n\n" + standing.strip() + "\n"
    body = INCLUDE_RE.sub(lambda _m: block, t.body).rstrip("\n") + "\n"
    return "\n".join(front) + body, {"model": model["alias"], "effort": effort, "tools": t.meta["tools"]}


def _is_generated(text: str) -> bool:
    return GENERATED_MARK in text


def render_all(workspace: Path, cfg: Optional[Mapping[str, Any]] = None, *, templates_dir: Optional[Path] = None,
               dry_run: bool = False, force: bool = False, out_dir: Optional[Path] = None) -> Report:
    """Render every template into ``<workspace>/.claude/agents/`` (or ``out_dir``).

    An existing file that this command did not generate is never overwritten unless ``force`` is set.
    """
    ws = Path(workspace)
    if cfg is None:
        cfg = cfgmod.load(ws) if (ws / "config" / "profile-wrap.json").exists() else cfgmod.defaults()
    report = Report()
    templates, standing = load_templates(templates_dir)
    for t in templates:
        report.problems += validate_template(t)
    if report.problems:
        return report
    dest = Path(out_dir) if out_dir else ws / ".claude" / "agents"
    for t in templates:
        text, info = render_agent(t, cfg, standing)
        target = dest / f"{t.name}.md"
        item = Rendered(t.name, str(target), "", model=info["model"], effort=info["effort"], tools=info["tools"])
        old = target.read_text(encoding="utf-8") if target.is_file() else None
        if old is not None and old.replace("\r\n", "\n") == text:
            item.status = "unchanged"
        elif old is not None and not _is_generated(old) and not force:
            item.status, item.detail = "refused", "an agent file with this name exists and was not generated by profile-wrap; use --force to replace it"
        elif dry_run:
            item.status = "would-write"
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            atomic_write_text(target, text)
            item.status = "written"
        report.items.append(item)
    return report


def check(workspace: Path, cfg: Optional[Mapping[str, Any]] = None, **kw: Any) -> List[str]:
    """Names of rendered agents that are missing or differ from what a render would write now."""
    rep = render_all(workspace, cfg, dry_run=True, **kw)
    return [i.name for i in rep.items if i.status in ("would-write", "refused")]


# --------------------------------------------------------------------------- command line

def _ws(args: argparse.Namespace) -> Path:
    from .cli import resolve_workspace
    return resolve_workspace(args)


def _cmd_render(args: argparse.Namespace) -> int:
    ws = _ws(args)
    try:
        rep = render_all(ws, dry_run=args.dry_run or args.check, force=args.force)
    except (AgentError, cfgmod.ConfigError, claude_runner.ToolPolicyError, OSError) as exc:
        print(f"FAIL {exc}")
        return policy.EXIT_FAIL
    if args.json:
        print(json.dumps({"ok": rep.ok, "problems": rep.problems,
                          "items": [i.__dict__ for i in rep.items]}, indent=2, ensure_ascii=False))
    else:
        for p in rep.problems:
            print(f"FAIL {p}")
        for i in rep.items:
            print(f"{i.status:11} {i.name:24} {i.model}/{i.effort}" + (f"  {i.detail}" if i.detail else ""))
    stale = [i for i in rep.items if i.status in ("would-write", "refused")]
    if args.check and stale:
        print(f"FAIL {len(stale)} agent files are out of date: run `profile-wrap agents render`")
        return policy.EXIT_FAIL
    return policy.EXIT_OK if rep.ok else policy.EXIT_FAIL


def _cmd_list(args: argparse.Namespace) -> int:
    try:
        templates, _ = load_templates()
    except AgentError as exc:
        print(f"FAIL {exc}")
        return policy.EXIT_FAIL
    rows = [{"name": t.name, "tier": t.meta.get("tier"), "effort": t.meta.get("effort"),
             "tools": t.meta.get("tools")} for t in templates]
    if args.json:
        print(json.dumps(rows, indent=2))
    else:
        for r in rows:
            print(f"{r['name']:24} {r['tier']:9} {r['effort']:7} {r['tools']}")
    return policy.EXIT_OK


def register(subparsers: Any) -> None:
    p = subparsers.add_parser("agents", help="render the agent templates with the model tier map")
    sub = p.add_subparsers(dest="agents_cmd", required=True)
    r = sub.add_parser("render", help="write the agents into .claude/agents/")
    r.add_argument("--workspace")
    r.add_argument("--profile")
    r.add_argument("--json", action="store_true")
    r.add_argument("--dry-run", action="store_true")
    r.add_argument("--check", action="store_true", help="exit 1 if a rendered agent is missing or stale")
    r.add_argument("--force", action="store_true", help="replace an agent file profile-wrap did not generate")
    r.set_defaults(func=_cmd_render)
    ls = sub.add_parser("list", help="the shipped templates")
    ls.add_argument("--json", action="store_true")
    ls.set_defaults(func=_cmd_list)
