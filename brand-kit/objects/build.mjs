// Packs objects/core/*.svg and objects/maker/*.svg into ../motion/objects.data.js (one JS module core.js imports)
// and writes preview.html (a contact sheet). Run: node brand-kit/objects/build.mjs
// A project-local motion/ copy then needs only core.js, objects.data.js, motion.css (and identity.js if it uses the card).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const out = {};
const packs = {};
for (const pack of ["core", "maker"]) {
  const p = join(dir, pack);
  if (!existsSync(p)) continue;
  for (const f of readdirSync(p).filter((n) => n.endsWith(".svg")).sort()) {
    const name = f.slice(0, -4);
    packs[name] = pack;
    out[name] = readFileSync(join(p, f), "utf8")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/>\s+</g, "><")
      .replace(/\s*\n\s*/g, " ")
      .trim();
  }
}
const js = `/* GENERATED by brand-kit/objects/build.mjs from objects/core and objects/maker. Do not edit; edit the .svg files and rebuild. */
export const SVG = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(join(dir, "..", "motion", "objects.data.js"), js);
const cells = Object.keys(out).map((n) => `<figure><figcaption>${n} <small>${packs[n]}</small></figcaption><img src="${packs[n]}/${n}.svg"></figure>`).join("\n");
writeFileSync(join(dir, "preview.html"), `<!doctype html><meta charset="utf-8"><title>objects</title>
<style>body{font:14px sans-serif;background:#e9edf2;margin:24px}main{display:grid;grid-template-columns:repeat(6,1fr);gap:16px}
figure{margin:0;background:#fff;border-radius:8px;padding:12px;text-align:center}img{width:120px;height:120px;object-fit:contain}small{color:#678}</style>
<main>
${cells}
</main>
`);
console.log("objects.data.js:", Object.keys(out).length, "objects", (js.length / 1024).toFixed(1) + " KB");
